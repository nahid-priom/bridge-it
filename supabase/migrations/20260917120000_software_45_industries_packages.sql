alter table public.catalog_industries
  add column if not exists taxonomy_type text not null default 'industry',
  add column if not exists is_featured boolean not null default false,
  add column if not exists primary_keyword text,
  add column if not exists secondary_keywords text[] not null default '{}',
  add column if not exists canonical_path text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'catalog_industries_taxonomy_type_check'
  ) then
    alter table public.catalog_industries
      add constraint catalog_industries_taxonomy_type_check
      check (taxonomy_type in ('industry', 'business_function', 'service_vertical'));
  end if;
end $$;

alter table public.software_packages
  add column if not exists tier text,
  add column if not exists payment_type text not null default 'one_time',
  add column if not exists target_business_size text,
  add column if not exists badge text,
  add column if not exists is_recommended boolean not null default false;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'software_packages_tier_check'
  ) then
    alter table public.software_packages
      add constraint software_packages_tier_check
      check (
        tier is null
        or tier in ('starter', 'basic', 'standard', 'professional', 'enterprise', 'advanced')
      );
  end if;
end $$;

create unique index if not exists idx_software_packages_project_tier_active
  on public.software_packages (project_id, tier)
  where deleted_at is null and tier is not null;

create index if not exists idx_catalog_industries_featured
  on public.catalog_industries (category_root, is_featured, sort_order)
  where deleted_at is null and active = true;

