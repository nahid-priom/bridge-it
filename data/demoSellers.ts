function enrichServices(services: MarketplaceService[]): MarketplaceService[] {
  const slugs = SELLERS.map((s) => s.slug);
  const byCat: Record<string, string> = {
    'software-development': 'code-factory',
    'web-development': 'tanvir-ahmed',
    'app-development': 'appcraft-studio',
    'digital-marketing': 'seo-pro-bd',
    'ai-automations': 'ai-experts-bd',
  };

  return services.map((svc, i) => {
    const slug =
      byCat[svc.categorySlug] ??
      slugs[i % slugs.length];
    const seller = SELLERS.find((s) => s.slug === slug)!;
    return {
      ...svc,
      sellerId: seller.id,
      sellerSlug: seller.slug,
      sellerName: seller.fullName,
      sellerLevel: seller.sellerLevel,
      sellerAvatarUrl: seller.avatarUrl,
      sellerRating: seller.rating,
      sellerCity: seller.city,
    };
  });
}

let cachedServices: MarketplaceService[] | null = null;

function getEnrichedServices(): MarketplaceService[] {
  if (!cachedServices) {
    cachedServices = enrichServices(getMarketplaceFallbackData().services);
  }
  return cachedServices;
}

